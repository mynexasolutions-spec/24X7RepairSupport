export function getBrandData(slug) {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();
  
  if (brandDetails[normalized]) {
    return brandDetails[normalized];
  }

  for (const key of Object.keys(brandDetails)) {
    const item = brandDetails[key];
    if (item.aliases && item.aliases.includes(normalized)) {
      return item;
    }
  }

  return null;
}

export function getRelatedBrands(slug) {
  const current = getBrandData(slug);
  const currentSlug = current ? current.slug : slug;

  return Object.keys(brandDetails)
    .filter(key => brandDetails[key].slug !== currentSlug)
    .map(key => brandDetails[key]);
}
